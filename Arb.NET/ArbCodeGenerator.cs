#if !ARB_GENERATOR
using System.IO;
#endif
using System.Text;

namespace Arb.NET;

/// <summary>
/// Generates C# code from parsed .arb documents
/// </summary>
public class ArbCodeGenerator {
    private readonly string? newLine;

    public ArbCodeGenerator() { }

    // .editorconfig inferred new line, or <see cref="Environment.NewLine"/> fallback.
    public ArbCodeGenerator(string? newLine) {
        this.newLine = newLine;
    }

    /// <summary>
    /// Generates a C# class from an ARB document
    /// </summary>
    public string GenerateClass(ArbDocument document, string className, string namespaceName,
        IReadOnlyDictionary<string, List<ArbParameterDefinition>>? paramOverrides = null) {
        StringBuilder sb = new();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine($"// Locale: {document.Locale}");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine($"public static class {className} {{");

        GenerationContext context = new();
        foreach (ArbEntry entry in document.Entries.Values) {
            GenerateEntry(sb, entry, context, paramOverrides);
        }

        if (context.UsesPluralCategories) {
            PluralRules.AppendCategoryMethod(sb, PLURAL_CATEGORY_METHOD, document.Locale);
        }

        sb.AppendLine("}");

        return NewLineHelper.Normalize(sb.ToString(), newLine);
    }

#if !ARB_GENERATOR
    /// <summary>
    /// Parses an .arb file and writes a generated C# file to <paramref name="outputPath"/>
    /// </summary>
    public void GenerateClassFile(string arbFilePath, string outputPath, string className, string namespaceName) {
        ArbParseResult result = new ArbParser().Parse(arbFilePath);
        if (!result.ValidationResults.IsValid) {
            // TODO(handle)
            return;
        }
        string source = GenerateClass(result.Document!, className, namespaceName);
        Directory.CreateDirectory(Path.GetDirectoryName(outputPath) ?? ".");
        File.WriteAllText(outputPath, source, Constants.UTF8_NO_BOM);
    }
#endif

    private const string PLURAL_CATEGORY_METHOD = "__ArbPluralCategory";

    private sealed class GenerationContext {
        public bool UsesPluralCategories { get; set; }
    }

    private static void GenerateEntry(StringBuilder sb, ArbEntry entry, GenerationContext context,
        IReadOnlyDictionary<string, List<ArbParameterDefinition>>? paramOverrides = null) {
        // Issue 1: Detect malformed plurals before anything else
        if (entry.TryDetectMangledPlural(out string? diagnostic)) {
            string pascalKey = StringHelper.ToPascalCase(entry.Key);
            sb.AppendLine();
            sb.AppendLine($"#warning {diagnostic}");
            sb.AppendLine($"    public static string {pascalKey}() {{");
            sb.AppendLine($"        throw new System.NotSupportedException(\"{StringHelper.JsonString(diagnostic!)}\");");
            sb.AppendLine($"    }}");
            return;
        }

        if (entry.IsParametric(out List<ArbParameterDefinition> defs)) {
            string paramList = BuildParamList(defs);

            sb.AppendLine();
            BuildSummaryTag(sb, entry, defs);
            sb.AppendLine($"    public static string {StringHelper.ToPascalCase(entry.Key)}({paramList}) {{");
            HashSet<string> intNames = GetIntParameterNames(defs);
            Dictionary<int, string> pluralVariables = BuildPluralizationDefs(sb, defs, intNames, context);
            sb.AppendLine($"        return {BuildFormattedString(entry, defs, intNames, pluralVariables)};");
            sb.AppendLine($"    }}");
        }
        else if (paramOverrides != null &&
                 paramOverrides.TryGetValue(entry.Key, out List<ArbParameterDefinition>? overrideDefs)) {
            // Issue 2: Another locale is parametric for this key — generate a method with matching signature
            string paramList = BuildParamList(overrideDefs);
            sb.AppendLine();
            BuildSummaryTag(sb, entry);
            sb.AppendLine($"    public static string {StringHelper.ToPascalCase(entry.Key)}({paramList}) {{");
            sb.AppendLine($"        return \"{StringHelper.JsonString(entry.Value)}\";");
            sb.AppendLine($"    }}");
        }
        else {
            sb.AppendLine();
            BuildSummaryTag(sb, entry);
            sb.AppendLine($"    public static string {StringHelper.ToPascalCase(entry.Key)}");
            sb.AppendLine($"        => \"{StringHelper.JsonString(entry.Value)}\";");
        }
    }

    /// <summary>
    /// Returns a valid C# identifier for the given ARB parameter name.
    /// Numeric names like "0" are prefixed with "_" to produce "_0".
    /// </summary>
    private static string ToIdentifier(string name) =>
        char.IsDigit(name[0]) ? "_" + name : name;

    /// <summary>
    /// Distinct parameter names in order of first appearance. A name repeated in the value
    /// (e.g. <c>"{a} and {a}"</c>, or <c>{name}</c> in several plural forms) becomes a single parameter.
    /// </summary>
    private static List<string> GetDistinctParameterNames(List<ArbParameterDefinition> defs) {
        List<string> names = [];
        HashSet<string> seen = new(StringComparer.Ordinal);
        foreach (ArbParameterDefinition def in defs) {
            if (seen.Add(def.Name)) names.Add(def.Name);
        }
        return names;
    }

    /// <summary>Names used as a plural selector anywhere in the value — these parameters are <c>int</c>.</summary>
    private static HashSet<string> GetIntParameterNames(List<ArbParameterDefinition> defs) {
        return new HashSet<string>(
            defs.OfType<ArbPluralizationParameterDefinition>().Select(d => d.Name),
            StringComparer.Ordinal
        );
    }

    private static string BuildParamList(List<ArbParameterDefinition> defs) {
        HashSet<string> intNames = GetIntParameterNames(defs);
        return string.Join(", ", GetDistinctParameterNames(defs)
                     .Select(name => (intNames.Contains(name) ? "int " : "object ") + ToIdentifier(name))
               );
    }

    private static string BuildArgList(List<ArbParameterDefinition> defs) {
        return string.Join(", ", GetDistinctParameterNames(defs).Select(ToIdentifier));
    }

    private static List<ArbParameterDefinition> GetTopLevelDefs(List<ArbParameterDefinition> defs) {
        List<ArbPluralizationParameterDefinition> plurals = defs.OfType<ArbPluralizationParameterDefinition>().ToList();
        return defs
            .Where(d => !plurals.Exists(p => !ReferenceEquals(p, d) &&
                                             d.StartIndex > p.StartIndex &&
                                             d.EndIndex <= p.EndIndex))
            .ToList();
    }

    private static string BuildFormattedString(ArbEntry entry, List<ArbParameterDefinition> defs,
        HashSet<string> intNames, Dictionary<int, string> pluralVariables) {
        return BuildStringExpression(entry.Value, GetTopLevelDefs(defs), intNames,
                                     plural => pluralVariables[plural.StartIndex]);
    }

    private static string BuildStringExpression(string value, List<ArbParameterDefinition> defs,
        HashSet<string> intNames, Func<ArbPluralizationParameterDefinition, string> pluralExpression) {
        StringBuilder sb = new();
        int index = 0;

        sb.Append('"');

        while (index < value.Length) {
            char current = value[index];

            if (current == '\\') {
                // Handle escaped characters
                if (index + 1 < value.Length) {
                    AppendEscapedChar(sb, value[index + 1]);
                    index += 2;
                    continue;
                }
            }

            if (defs.Find(f => f.StartIndex == index) is { } def) {
                sb.Append("\" + ");
                if (def is ArbPluralizationParameterDefinition pluralDef) {
                    sb.Append(pluralExpression(pluralDef));
                }
                else {
                    sb.Append(ToIdentifier(def.Name));
                    sb.Append(intNames.Contains(def.Name) ? ".ToString()" : "?.ToString()");
                }
                sb.Append(" + \"");
                index = def.EndIndex;
                continue;
            }

            AppendEscapedChar(sb, current);
            index++;
        }

        sb.Append('"');
        return sb.ToString();
    }

    private static void AppendEscapedChar(StringBuilder sb, char c) {
        switch (c) {
            case '"': sb.Append("\\\""); break;
            case '\\': sb.Append("\\\\"); break;
            case '\n': sb.Append("\\n"); break;
            case '\r': sb.Append("\\r"); break;
            case '\t': sb.Append("\\t"); break;
            default: sb.Append(c); break;
        }
    }

    private static Dictionary<int, string> BuildPluralizationDefs(StringBuilder sb, List<ArbParameterDefinition> defs,
        HashSet<string> intNames, GenerationContext context) {
        Dictionary<int, string> variables = [];
        HashSet<string> usedVariables = new(StringComparer.Ordinal);

        foreach (ArbParameterDefinition def in GetTopLevelDefs(defs)) {
            if (def is not ArbPluralizationParameterDefinition pluralDef) continue;

            string id = ToIdentifier(pluralDef.Name);
            string variable = $"@selectedContent_{id}";
            for (int suffix = 2; !usedVariables.Add(variable); suffix++) {
                variable = $"@selectedContent_{id}_{suffix}";
            }
            variables[pluralDef.StartIndex] = variable;

            List<(string Pattern, string Expression)> arms = BuildPluralArms(pluralDef, intNames, context,
                out List<(string Pattern, string Expression)>? categoryArms);

            sb.AppendLine($"        var {variable} = ({id}) switch {{");
            foreach ((string pattern, string expression) in arms) {
                sb.AppendLine($"            {pattern} => {expression},");
            }
            if (categoryArms != null) {
                sb.AppendLine($"            _ => {PLURAL_CATEGORY_METHOD}({id}) switch {{");
                foreach ((string pattern, string expression) in categoryArms) {
                    sb.AppendLine($"                {pattern} => {expression},");
                }
                sb.AppendLine($"                _ => {BuildFormExpression(pluralDef.OtherParameter, intNames, context)}");
                sb.AppendLine("            }");
            }
            else {
                sb.AppendLine($"            _ => {BuildFormExpression(pluralDef.OtherParameter, intNames, context)}");
            }
            sb.AppendLine("        };");
        }

        return variables;
    }

    private static List<(string Pattern, string Expression)> BuildPluralArms(
        ArbPluralizationParameterDefinition pluralDef,
        HashSet<string> intNames,
        GenerationContext context,
        out List<(string Pattern, string Expression)>? categoryArms) {
        List<(string, string)> arms = [];
        foreach (KeyValuePair<int, string> form in pluralDef.CountableParameters) {
            arms.Add((form.Key.ToString(), BuildFormExpression(form.Value, intNames, context)));
        }

        categoryArms = null;
        if (pluralDef.CategoryParameters.Count == 0) return arms;

        context.UsesPluralCategories = true;
        (string Category, int Number)[] exactCategories = [(PluralRules.ZERO, 0), (PluralRules.ONE, 1), (PluralRules.TWO, 2)];
        foreach ((string category, int number) in exactCategories) {
            if (pluralDef.CategoryParameters.TryGetValue(category, out string? content) &&
                !pluralDef.CountableParameters.ContainsKey(number)) {
                arms.Add((number.ToString(), BuildFormExpression(content, intNames, context)));
            }
        }

        categoryArms = [];
        foreach (string category in PluralRules.Categories) {
            if (pluralDef.CategoryParameters.TryGetValue(category, out string? content)) {
                categoryArms.Add(($"\"{category}\"", BuildFormExpression(content, intNames, context)));
            }
        }
        return arms;
    }

    private static string BuildInlinePluralExpression(ArbPluralizationParameterDefinition pluralDef,
        HashSet<string> intNames, GenerationContext context) {
        string id = ToIdentifier(pluralDef.Name);
        List<(string Pattern, string Expression)> arms = BuildPluralArms(pluralDef, intNames, context,
            out List<(string Pattern, string Expression)>? categoryArms);
        string other = BuildFormExpression(pluralDef.OtherParameter, intNames, context);
        string fallback = categoryArms == null
            ? other
            : $"{PLURAL_CATEGORY_METHOD}({id}) switch {{ " +
              string.Concat(categoryArms.Select(a => $"{a.Pattern} => {a.Expression}, ")) +
              $"_ => {other} }}";
        return $"(({id}) switch {{ " +
               string.Concat(arms.Select(a => $"{a.Pattern} => {a.Expression}, ")) +
               $"_ => {fallback} }})";
    }

    private static string BuildFormExpression(string content, HashSet<string> intNames, GenerationContext context) {
        List<ArbParameterDefinition> innerDefs = ArbEntry.ParseParameters(content);
        foreach (ArbPluralizationParameterDefinition nested in innerDefs.OfType<ArbPluralizationParameterDefinition>()) {
            intNames.Add(nested.Name);
        }
        return BuildStringExpression(content, GetTopLevelDefs(innerDefs), intNames,
                                     nested => BuildInlinePluralExpression(nested, intNames, context));
    }

    private static void BuildSummaryTag(StringBuilder sb, ArbEntry entry, List<ArbParameterDefinition>? defs = null) {
        string? description = entry.Metadata?.Description;
        string renderedValue = StringHelper.XmlEscape(RenderEntryValueForDoc(entry));

        if (!string.IsNullOrWhiteSpace(description)) {
            sb.AppendLine($"    /// <summary>{description}</summary>");
        }
        sb.AppendLine($"    /// <returns>{renderedValue}</returns>");

        // Issue 4: Emit concrete plural examples
        string? examples = RenderPluralExamplesForDoc(entry, defs);
        if (examples != null) {
            sb.AppendLine($"    /// <example>{StringHelper.XmlEscape(examples)}</example>");
        }
    }

    /// <summary>
    /// Generates a dispatcher class that routes localization calls to the correct
    /// locale-specific static class based on a <see cref="System.Globalization.CultureInfo"/>.
    /// The <paramref name="defaultLocale"/> document is authoritative for entry signatures.
    /// When <paramref name="enumLocalizations"/> is provided, a <c>Localize(EnumType)</c>
    /// overload is emitted for each enum so callers can write <c>l.Localize(myEnumValue)</c>.
    /// </summary>
    public string GenerateDispatcherClass(
        IReadOnlyList<(ArbDocument Document, string ClassName)> locales,
        ArbDocument defaultLocale,
        string baseClassName,
        string namespaceName,
        IReadOnlyList<EnumLocalizationInfo>? enumLocalizations = null
    ) {
        StringBuilder sb = new();
        string availableLocales = string.Join(", ", locales.Select(l => l.Document.Locale));

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine($"// Available locales: {availableLocales}");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {namespaceName};");
        sb.AppendLine();
        sb.AppendLine($"public partial class {baseClassName} : global::Arb.NET.IArbLocale {{");
        sb.AppendLine($"    private readonly System.Globalization.CultureInfo _culture;");
        sb.AppendLine();
        sb.AppendLine($"    public {baseClassName}(System.Globalization.CultureInfo culture) {{");
        sb.AppendLine($"        _culture = culture;");
        sb.AppendLine($"    }}");
        sb.AppendLine();

        // ResolveLocale — maps a CultureInfo to a normalized locale key
        sb.AppendLine($"    private static string ResolveLocale(System.Globalization.CultureInfo culture) {{");
        sb.AppendLine($"        var name = culture.Name.Replace(\"-\", \"_\");");
        sb.AppendLine($"        return name switch {{");
        foreach ((ArbDocument doc, string _) in locales) {
            string normalized = StringHelper.JsonString(StringHelper.NormalizeLocale(doc.Locale));
            sb.AppendLine($"            \"{normalized}\" => \"{normalized}\",");
        }
        sb.AppendLine($"            _ => TryParent(culture)");
        sb.AppendLine($"        }};");
        sb.AppendLine($"    }}");
        sb.AppendLine();

        // TryParent — walks up to neutral culture, then throws
        sb.AppendLine($"    private static string TryParent(System.Globalization.CultureInfo culture) {{");
        sb.AppendLine($"        if (!culture.IsNeutralCulture) {{");
        sb.AppendLine($"            var parent = culture.Parent;");
        sb.AppendLine($"            if (!string.IsNullOrEmpty(parent.Name))");
        sb.AppendLine($"                return ResolveLocale(parent);");
        sb.AppendLine($"        }}");
        sb.AppendLine($"        throw new System.NotSupportedException(");
        sb.AppendLine($"            $\"No localization found for '{{culture.Name}}'. Available: {availableLocales}\");");
        sb.AppendLine($"    }}");

        // Build a lookup: locale key → class name, for use in switch arms
        Dictionary<string, string> localeToClass = locales.ToDictionary(
            l => StringHelper.NormalizeLocale(l.Document.Locale),
            l => l.ClassName);

        // Emit one member per entry in the default-locale document
        foreach (ArbEntry? entry in defaultLocale.Entries.Values) {
            sb.AppendLine();
            GenerateDispatcherEntry(sb, entry, locales, localeToClass, availableLocales);
        }

        AppendDictProperty(sb, defaultLocale);

        // Emit Localize(EnumType) overloads for each [ArbLocalize] enum
        if (enumLocalizations != null) {
            foreach (EnumLocalizationInfo info in enumLocalizations) {
                AppendEnumLocalizeMethod(sb, info.FullName, info.SimpleName, info.Members);
            }
        }

        sb.AppendLine("}");
        return NewLineHelper.Normalize(sb.ToString(), newLine);
    }

    private static void GenerateDispatcherEntry(
        StringBuilder sb,
        ArbEntry defaultEntry,
        IReadOnlyList<(ArbDocument Document, string ClassName)> locales,
        Dictionary<string, string> localeToClass,
        string availableLocales
    ) {

        // If the default entry is a mangled plural, emit a warning stub and skip dispatcher routing
        if (defaultEntry.TryDetectMangledPlural(out string? diagnostic)) {
            string pascalKey2 = StringHelper.ToPascalCase(defaultEntry.Key);
            sb.AppendLine();
            sb.AppendLine($"#warning {diagnostic}");
            sb.AppendLine($"    public string {pascalKey2}() {{");
            sb.AppendLine($"        throw new System.NotSupportedException(\"{StringHelper.JsonString(diagnostic!)}\");");
            sb.AppendLine($"    }}");
            return;
        }

        bool isParametric = defaultEntry.IsParametric(out List<ArbParameterDefinition> defs);
        string pascalKey = StringHelper.ToPascalCase(defaultEntry.Key);

        // Build a set of locale keys whose documents actually contain this entry.
        HashSet<string> localesWithEntry = new(
            locales
                .Where(l => l.Document.Entries.ContainsKey(defaultEntry.Key))
                .Select(l => StringHelper.NormalizeLocale(l.Document.Locale))
        );

        BuildDispatcherSummaryTag(sb, defaultEntry, locales, localesWithEntry);

        if (isParametric) {
            string paramList = BuildParamList(defs);
            string argList = BuildArgList(defs);
            sb.AppendLine($"    public string {pascalKey}({paramList}) {{");
            sb.AppendLine($"        return ResolveLocale(_culture) switch {{");
            foreach ((ArbDocument doc, string _) in locales) {
                string key = StringHelper.NormalizeLocale(doc.Locale);
                string arm = ResolveEntryArm(key, localesWithEntry, localeToClass, isParametric: true, pascalKey, argList);
                sb.AppendLine($"            \"{StringHelper.JsonString(key)}\" => {arm},");
            }
            sb.AppendLine($"            _ => throw new System.NotSupportedException(");
            sb.AppendLine($"                $\"No localization found for '{{_culture.Name}}'. Available: {availableLocales}\")");
            sb.AppendLine($"        }};");
            sb.AppendLine($"    }}");
        }
        else {
            sb.AppendLine($"    public string {pascalKey} => ResolveLocale(_culture) switch {{");
            foreach ((ArbDocument doc, string _) in locales) {
                string key = StringHelper.NormalizeLocale(doc.Locale);
                string arm = ResolveEntryArm(key, localesWithEntry, localeToClass, isParametric: false, pascalKey, argList: null);
                sb.AppendLine($"        \"{StringHelper.JsonString(key)}\" => {arm},");
            }
            sb.AppendLine($"        _ => throw new System.NotSupportedException(");
            sb.AppendLine($"            $\"No localization found for '{{_culture.Name}}'. Available: {availableLocales}\")");
            sb.AppendLine($"    }};");
        }
    }

    private static void BuildDispatcherSummaryTag(
        StringBuilder sb,
        ArbEntry defaultEntry,
        IReadOnlyList<(ArbDocument Document, string ClassName)> locales,
        HashSet<string> localesWithEntry
    ) {

        string? description = defaultEntry.Metadata?.Description;

        sb.AppendLine($"    /// <summary>");
        if (!string.IsNullOrWhiteSpace(description)) {
            sb.AppendLine($"    /// {description}");
        }
        sb.AppendLine($"    /// <list type=\"table\">");
        sb.AppendLine($"    /// <listheader><term>Locale</term><description>Value</description></listheader>");

        List<(string Term, string Description)> rows = [];
        List<string> pendingFallback = [];
        string? pendingFallbackTarget = null;

        foreach ((ArbDocument doc, string _) in locales) {
            string normalizedKey = StringHelper.NormalizeLocale(doc.Locale);
            string localeLabel = doc.Locale ?? normalizedKey;

            if (localesWithEntry.Contains(normalizedKey)) {
                FlushPendingFallback();
                ArbEntry localeEntry = doc.Entries[defaultEntry.Key];
                string rendered = StringHelper.XmlEscape(RenderEntryValueForDoc(localeEntry));
                rows.Add((localeLabel, rendered));
            }
            else {
                string? fallback = ResolveFallbackLocale(normalizedKey, localesWithEntry);

                // Group with previous fallback row only if same target
                if (fallback != null && fallback == pendingFallbackTarget) {
                    pendingFallback.Add(localeLabel);
                }
                else {
                    FlushPendingFallback();
                    if (fallback != null) {
                        pendingFallback.Add(localeLabel);
                        pendingFallbackTarget = fallback;
                    }
                    else {
                        rows.Add((localeLabel, "[MISSING]"));
                    }
                }
            }
        }
        FlushPendingFallback();

        foreach ((string term, string desc) in rows) {
            sb.AppendLine($"    /// <item><term>{term}</term><description>{desc}</description></item>");
        }

        sb.AppendLine($"    /// </list>");
        sb.AppendLine($"    /// </summary>");

        string? examples = RenderPluralExamplesForDoc(defaultEntry);
        if (examples != null) {
            sb.AppendLine($"    /// <example>{StringHelper.XmlEscape(examples)}</example>");
        }
        return;

        void FlushPendingFallback() {
            if (pendingFallback.Count == 0) return;
            rows.Add((string.Join(", ", pendingFallback), $"[fallback to {pendingFallbackTarget}]"));
            pendingFallback.Clear();
            pendingFallbackTarget = null;
        }
    }

    /// <summary>
    /// Appends a <c>Localize(EnumType)</c> method to <paramref name="sb"/> inside the
    /// dispatcher class body.  Each arm delegates to the already-generated dispatcher
    /// property for the corresponding ARB key, so locale routing is handled automatically.
    /// </summary>
    private static void AppendEnumLocalizeMethod(
        StringBuilder sb,
        string enumFullName,
        string enumSimpleName,
        IReadOnlyList<string> members
    ) {
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Returns the localized display name for a <see cref=\"{enumFullName}\"/> value.</summary>");
        sb.AppendLine($"    public string Localize({enumFullName} value) {{");
        sb.AppendLine($"        return value switch {{");

        foreach (string member in members) {
            string camelKey = StringHelper.ToCamelCase(enumSimpleName) + StringHelper.ToPascalCase(member);
            sb.AppendLine($"            {enumFullName}.{member} => {StringHelper.ToPascalCase(camelKey)},");
        }

        sb.AppendLine($"            _ => value.ToString()");
        sb.AppendLine($"        }};");
        sb.AppendLine($"    }}");
    }

    private static void AppendDictProperty(StringBuilder sb, ArbDocument defaultLocale) {
        List<ArbEntry> simpleEntries = defaultLocale.Entries.Values
            .Where(e => !e.IsParametric(out _))
            .ToList();

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Returns the localized string for the given raw ARB key, or null if not found.</summary>");
        sb.AppendLine("    public string? this[string? key] => key switch {");
        foreach (ArbEntry entry in simpleEntries) {
            string pascal = StringHelper.ToPascalCase(entry.Key);
            sb.AppendLine($"        \"{StringHelper.JsonString(entry.Key)}\" => {pascal},");
            if (pascal != entry.Key) {
                sb.AppendLine($"        \"{StringHelper.JsonString(pascal)}\" => {pascal},");
            }
        }
        sb.AppendLine("        _ => null");
        sb.AppendLine("    };");
    }

    /// <summary>Walks the parent chain to find the nearest ancestor locale that has the entry. Returns null if none found.</summary>
    private static string? ResolveFallbackLocale(string normalizedLocale, HashSet<string> localesWithEntry) {
        string current = normalizedLocale;
        while (true) {
            int lastSep = current.LastIndexOf('_');
            if (lastSep < 0) return null;
            string suffix = current.Substring(lastSep + 1);
            string prefix = current.Substring(0, lastSep);
            // Try the suffix first (e.g. cs_en → en), then the prefix (e.g. en_US → en)
            if (localesWithEntry.Contains(suffix)) return suffix;
            if (localesWithEntry.Contains(prefix)) return prefix;
            current = prefix;
        }
    }

    /// <summary>
    /// Renders an entry's value into a human-readable string for use in XML doc comments.
    /// Plural parameters are expanded from <c>{count, plural, =0{...} other{...}}</c>
    /// into a compact inline notation: <c>{count, 0 - "...", 1 - "...", else "..."}</c>.
    /// Simple parameters and surrounding literal text are left as-is.
    /// </summary>
    private static string RenderEntryValueForDoc(ArbEntry entry) {
        if (!entry.IsParametric(out List<ArbParameterDefinition> defs)) {
            return entry.Value;
        }

        // Check if any def is a pluralization — if not, return the raw value unchanged.
        if (!defs.Exists(d => d is ArbPluralizationParameterDefinition)) {
            return entry.Value;
        }

        StringBuilder sb = new();
        int index = 0;

        while (index < entry.Value.Length) {
            // Handle escape sequences — pass them through verbatim
            if (entry.Value[index] == '\\' && index + 1 < entry.Value.Length) {
                sb.Append(entry.Value[index]);
                sb.Append(entry.Value[index + 1]);
                index += 2;
                continue;
            }

            // Check if a parameter starts here
            if (defs.Find(d => d.StartIndex == index) is { } def) {
                if (def is ArbPluralizationParameterDefinition pluralDef) {
                    // Build compact: {name, 0 - "...", 1 - "...", else "..."}
                    sb.Append('{');
                    sb.Append(pluralDef.Name);
                    foreach (KeyValuePair<int, string> kv in pluralDef.CountableParameters.OrderBy(kv => kv.Key)) {
                        sb.Append(", ");
                        sb.Append(kv.Key);
                        sb.Append(" - \"");
                        sb.Append(kv.Value);
                        sb.Append('"');
                    }
                    foreach (string category in PluralRules.Categories) {
                        if (!pluralDef.CategoryParameters.TryGetValue(category, out string? content)) continue;
                        sb.Append(", ");
                        sb.Append(category);
                        sb.Append(" - \"");
                        sb.Append(content);
                        sb.Append('"');
                    }
                    sb.Append(", else \"");
                    sb.Append(pluralDef.OtherParameter);
                    sb.Append("\"}");
                }
                else {
                    // Simple parameter — keep as {name}
                    sb.Append('{');
                    sb.Append(def.Name);
                    sb.Append('}');
                }
                index = def.EndIndex;
                continue;
            }

            sb.Append(entry.Value[index]);
            index++;
        }

        return sb.ToString();
    }

    /// <summary>
    /// Renders concrete plural examples for doc comments.
    /// For each plural parameter, produces lines like: 0 - "No items", 1 - "1 item", n - "n items"
    /// </summary>
    private static string? RenderPluralExamplesForDoc(ArbEntry entry, List<ArbParameterDefinition>? defs = null) {
        if (defs == null) {
            if (!entry.IsParametric(out var parsed)) return null;
            defs = parsed;
        }

        List<ArbPluralizationParameterDefinition> pluralDefs = defs
            .OfType<ArbPluralizationParameterDefinition>()
            .ToList();

        if (pluralDefs.Count == 0) return null;

        StringBuilder sb = new();
        foreach (ArbPluralizationParameterDefinition pluralDef in pluralDefs) {
            foreach (KeyValuePair<int, string> kv in pluralDef.CountableParameters.OrderBy(kv => kv.Key)) {
                if (sb.Length > 0) sb.Append(", ");
                string resolved = kv.Value.Replace($"{{{pluralDef.Name}}}", kv.Key.ToString());
                sb.Append($"{kv.Key} - \"{resolved}\"");
            }
            foreach (string category in PluralRules.Categories) {
                if (!pluralDef.CategoryParameters.TryGetValue(category, out string? content)) continue;
                if (sb.Length > 0) sb.Append(", ");
                sb.Append($"{category} - \"{content}\"");
            }
            if (!string.IsNullOrEmpty(pluralDef.OtherParameter)) {
                if (sb.Length > 0) sb.Append(", ");
                string resolved = pluralDef.OtherParameter.Replace($"{{{pluralDef.Name}}}", "n");
                sb.Append($"n - \"{resolved}\"");
            }
        }

        return sb.Length > 0 ? sb.ToString() : null;
    }

    /// <summary>
    /// Resolves the switch-arm expression for a given locale and entry key.
    /// <list type="bullet">
    ///   <item>If the locale's document has the entry, calls the locale class directly.</item>
    ///   <item>If missing and the locale is a sub-culture (e.g. <c>en_US</c>), walks up the
    ///         parent chain (<c>en_US</c> → <c>en</c>) to find the nearest ancestor that has it.</item>
    ///   <item>If no ancestor has the entry (neutral/root locale with no match), emits <c>"&lt;MISSING&gt;"</c>.</item>
    /// </list>
    /// </summary>
    private static string ResolveEntryArm(
        string normalizedLocale,
        HashSet<string> localesWithEntry,
        Dictionary<string, string> localeToClass,
        bool isParametric,
        string pascalKey,
        string? argList
    ) {

        string current = normalizedLocale;
        while (true) {
            if (localesWithEntry.Contains(current) && localeToClass.TryGetValue(current, out string? cls)) {
                return isParametric
                    ? $"{cls}.{pascalKey}({argList})"
                    : $"{cls}.{pascalKey}";
            }

            // Walk up the parent chain: try the suffix first (e.g. cs_en → en),
            // then the prefix (e.g. en_US → en).
            int lastSep = current.LastIndexOf('_');
            if (lastSep < 0) {
                return "\"<MISSING>\"";
            }

            string suffix = current.Substring(lastSep + 1);
            string prefix = current.Substring(0, lastSep);
            if (localesWithEntry.Contains(suffix) && localeToClass.TryGetValue(suffix, out string? suffixClass)) {
                return isParametric ? $"{suffixClass}.{pascalKey}({argList})" : $"{suffixClass}.{pascalKey}";
            }
            current = prefix;
        }
    }
